        static float Slope(float a,float b) {return a*b<=0?0:2*a*b/(a+b);}
        static float Hermite(float a,float b,float ma,float mb,float t) {
            return (2*t*t*t-3*t*t+1)*a+(t*t*t-2*t*t+t)*ma+(-2*t*t*t+3*t*t)*b+(t*t*t-t*t)*mb;
        }
        static float Ring(int row,float angle) {
            float phase=Mathf.Repeat(angle,360)/11.25f;int col=Mathf.FloorToInt(phase);float t=phase-col;
            float a=Radii[row*32+(col+31)%32],b=Radii[row*32+col],c=Radii[row*32+(col+1)%32],d=Radii[row*32+(col+2)%32];
            return Hermite(b,c,Slope(b-a,c-b),Slope(c-b,d-c),t);
        }
        static float Radius(float elevation,float angle) {
            float e=Mathf.Clamp(elevation,0,90);int row=0;while(row<Elevations.Length-2&&Elevations[row+1]<e)row++;
            float h=Elevations[row+1]-Elevations[row],a=Ring(row,angle),b=Ring(row+1,angle),s=(b-a)/h,ma=s,mb=s;
            if(row>0)ma=Slope((a-Ring(row-1,angle))/(Elevations[row]-Elevations[row-1]),s);
            if(row<Elevations.Length-2)mb=Slope(s,(Ring(row+2,angle)-b)/(Elevations[row+2]-Elevations[row+1]));
            float radius=Hermite(a,b,ma*h,mb*h,(e-Elevations[row])/h);
            if(elevation<0)radius=radius*(1-.10f*elevation*Mathf.Deg2Rad)/Mathf.Cos(elevation*Mathf.Deg2Rad);
            return radius;
        }
