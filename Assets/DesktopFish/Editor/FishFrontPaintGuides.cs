        static float Slope(float a,float b)=>a*b<=0?0:2*a*b/(a+b);
        static float Interpolate(float[] values,int i,float t) {
            float delta=values[i+1]-values[i];
            float ma=i==0?delta:Slope(values[i]-values[i-1],delta);
            float mb=i==values.Length-2?delta:Slope(delta,values[i+2]-values[i+1]);
            return (2*t*t*t-3*t*t+1)*values[i]+(t*t*t-2*t*t+t)*ma+(-2*t*t*t+3*t*t)*values[i+1]+(t*t*t-t*t)*mb;
        }
        static Vector3[][][] SmoothBrushes() {
            var result=new Vector3[Panels.Length][][];
            for(int panel=0;panel<Panels.Length;panel++) {
