                    float length=Vector2.Distance(start,end);var axis=(end-start).normalized;var cross=new Vector2(-axis.y,axis.x);
                    var left=new float[11];var right=new float[11];
                    for(int i=0;i<11;i++){left[i]=Vector2.Dot(new Vector2(raw[i].x,raw[i].y)-start,cross);right[i]=Vector2.Dot(new Vector2(raw[21-i].x,raw[21-i].y)-start,cross);}
