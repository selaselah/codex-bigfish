        static float Cubic(float a,float b,float ma,float mb,float h,float t) {
            float t2=t*t,t3=t2*t;return (2*t3-3*t2+1)*a+(t3-2*t2+t)*h*ma+(-2*t3+3*t2)*b+(t3-t2)*h*mb;
        }
        static float RowSlope(Vector3[] q,int i) {
            if(i==0)return (q[1].z-q[0].z)/(q[1].x-q[0].x);
            if(i==q.Length-1)return (q[i].z-q[i-1].z)/(q[i].x-q[i-1].x);
            float h=q[i].x-q[i-1].x,k=q[i+1].x-q[i].x;
            return Slope((q[i].z-q[i-1].z)/h,(q[i+1].z-q[i].z)/k,h,k);
        }
        static float RowValue(int row,float x,int kind) {
            var q=Rows[row];if(kind==1)return q[0].x;if(kind==2)return q[q.Length-1].x;
            x=Mathf.Clamp(x,q[0].x,q[q.Length-1].x);int i=0;while(i<q.Length-2&&x>q[i+1].x)i++;
            float h=q[i+1].x-q[i].x;return Cubic(q[i].z,q[i+1].z,RowSlope(q,i),RowSlope(q,i+1),h,(x-q[i].x)/h);
        }
        static float Surface(float x,float y,int kind) {
            int i=0;while(i<Rows.Length-2&&y>Rows[i+1][0].y)i++;
            float h=Rows[i+1][0].y-Rows[i][0].y,t=Mathf.Clamp01((y-Rows[i][0].y)/h);
            float a=RowValue(i,x,kind),b=RowValue(i+1,x,kind),d=(b-a)/h,ma=d,mb=d;
            if(i>0){float k=Rows[i][0].y-Rows[i-1][0].y;ma=Slope((a-RowValue(i-1,x,kind))/k,d,k,h);}
            if(i<Rows.Length-2){float k=Rows[i+2][0].y-Rows[i+1][0].y;mb=Slope(d,(RowValue(i+2,x,kind)-b)/k,h,k);}
            return Cubic(a,b,ma,mb,h,t);
        }
        public static float Depth(float existing,float x,float y,float facing) {
            if(y<=Rows[0][0].y||y>=Rows[Rows.Length-1][0].y||facing<=0)return existing;
            float lo=Surface(x,y,1),hi=Surface(x,y,2),side=x<0?x/lo:x/hi;
            float weight=(1-Mathf.SmoothStep(0,1,Mathf.InverseLerp(.80f,1.02f,side)))
                *Mathf.SmoothStep(0,1,Mathf.InverseLerp(.05f,.50f,facing))
                *Mathf.SmoothStep(0,1,Mathf.InverseLerp(.55125f,.570f,y))
                *(1-Mathf.SmoothStep(0,1,Mathf.InverseLerp(.845f,.895f,y)));
            return Mathf.Lerp(existing,Surface(x,y,0),weight);
        }
    }
