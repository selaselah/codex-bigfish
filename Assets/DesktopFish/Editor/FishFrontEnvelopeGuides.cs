        static float Tangent(float a,float b,float ha,float hb) {
            if(a*b<=0)return 0;
            return (ha+hb)/(ha/a+hb/b);
        }
        static float Cubic(float a,float b,float ma,float mb,float h,float t) {
            return Mathf.Clamp((2*t*t*t-3*t*t+1)*a+(t*t*t-2*t*t+t)*h*ma+(-2*t*t*t+3*t*t)*b+(t*t*t-t*t)*h*mb,Mathf.Min(a,b),Mathf.Max(a,b));
        }
        static float Across(int row,float x) {
            int start=row*Columns;float lo=Supports[start].x,hi=Supports[start+Columns-1].x;
            float f=Mathf.Clamp01((x-lo)/(hi-lo))*(Columns-1);int c=Mathf.Min(Columns-2,(int)f);float t=f-c;
