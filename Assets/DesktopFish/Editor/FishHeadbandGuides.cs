            int i=1;while(i<Stations.Length-1&&u>Stations[i])i++;
            return Vector3.Lerp(Points[(i-1)*5+column],Points[i*5+column],Mathf.InverseLerp(Stations[i-1],Stations[i],u));
        }
        static float Remap(float value,float[] from,float[] to) {
            int i=1;while(i<from.Length-1&&value>from[i])i++;
            return Mathf.Lerp(to[i-1],to[i],Mathf.InverseLerp(from[i-1],from[i],value));
        }
