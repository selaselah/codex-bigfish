        static float Slope(float a,float b,float ha,float hb) {
            if(a*b<=0)return 0;float wa=2*hb+ha,wb=hb+2*ha;return (wa+wb)/(wa/a+wb/b);
        }
        static float Cubic(float a,float b,float ma,float mb,float h,float t) {
            float t2=t*t,t3=t2*t;return (2*t3-3*t2+1)*a+(t3-2*t2+t)*h*ma+(-2*t3+3*t2)*b+(t3-t2)*h*mb;
        }
        static float R(int row,int col) {var p=Rows[row][(col%48+48)%48];return new Vector2(p.x,p.z).magnitude;}
        static float RowRadius(int row,float theta) {
            float f=Mathf.Repeat(theta/(Mathf.PI*2),1)*48;int col=Mathf.FloorToInt(f);float t=f-col;
            float a=R(row,col),b=R(row,col+1),d=b-a;
            return Cubic(a,b,Slope(a-R(row,col-1),d,1,1),Slope(d,R(row,col+2)-b,1,1),1,t);
        }
        public static float Radius(float y,float theta) {
            int row=0;while(row<Rows.Length-2&&Rows[row+1][0].y<y)row++;
            float h=Rows[row+1][0].y-Rows[row][0].y,t=Mathf.Clamp01((y-Rows[row][0].y)/h);
            float a=RowRadius(row,theta),b=RowRadius(row+1,theta),d=(b-a)/h,ma=d,mb=d;
